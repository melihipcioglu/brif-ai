"""Shared enums for BRIF.AI conversation catalog v0 contracts."""

from __future__ import annotations

import sys
from enum import Enum

if sys.version_info >= (3, 11):  # noqa: UP036
    from enum import StrEnum
else:  # pragma: no cover - Python 3.10 local tooling compatibility

    class StrEnum(str, Enum):  # noqa: UP042
        pass


class ConversationModule(StrEnum):
    PROJECT_CONTEXT = "PROJECT_CONTEXT"
    STAKEHOLDERS = "STAKEHOLDERS"
    DAILY_ROUTINES = "DAILY_ROUTINES"
    SPACE_REQUIREMENTS = "SPACE_REQUIREMENTS"
    SPATIAL_RELATIONSHIPS = "SPATIAL_RELATIONSHIPS"
    PRIVACY_AND_SOCIAL_USE = "PRIVACY_AND_SOCIAL_USE"
    ACCESSIBILITY = "ACCESSIBILITY"
    ENVIRONMENTAL_COMFORT = "ENVIRONMENTAL_COMFORT"
    STORAGE_AND_SERVICE = "STORAGE_AND_SERVICE"
    FUTURE_CHANGE = "FUTURE_CHANGE"
    CONFLICT_RESOLUTION = "CONFLICT_RESOLUTION"
    FINAL_CONFIRMATION = "FINAL_CONFIRMATION"


class AnswerType(StrEnum):
    FREE_TEXT = "FREE_TEXT"
    SINGLE_CHOICE = "SINGLE_CHOICE"
    MULTIPLE_CHOICE = "MULTIPLE_CHOICE"
    BOOLEAN = "BOOLEAN"
    INTEGER = "INTEGER"
    CONFIRMATION = "CONFIRMATION"


class QuestionStatus(StrEnum):
    DRAFT = "DRAFT"
    APPROVED = "APPROVED"
    RETIRED = "RETIRED"


class FulfillmentPolicy(StrEnum):
    VALID_ANSWER = "VALID_ANSWER"
    CONFIRMED_BRIEF_PROPOSAL = "CONFIRMED_BRIEF_PROPOSAL"


class ConditionType(StrEnum):
    ANSWER_EQUALS = "ANSWER_EQUALS"
    ANSWER_INCLUDES = "ANSWER_INCLUDES"
    ANSWER_GREATER_THAN = "ANSWER_GREATER_THAN"
    QUESTION_ANSWERED = "QUESTION_ANSWERED"
    QUESTION_SKIPPED = "QUESTION_SKIPPED"
    BRIEF_ITEM_CONFIRMED = "BRIEF_ITEM_CONFIRMED"
    CONTRADICTION_OPEN = "CONTRADICTION_OPEN"
