"""Shared enums for scientific publication validation v0."""

from __future__ import annotations

import sys
from enum import Enum

if sys.version_info >= (3, 11):  # noqa: UP036
    from enum import StrEnum
else:  # pragma: no cover - Python 3.10 local tooling compatibility

    class StrEnum(str, Enum):  # noqa: UP042
        pass


class PublicationIssueSeverity(StrEnum):
    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"

    @property
    def is_blocking(self) -> bool:
        return self in (PublicationIssueSeverity.ERROR, PublicationIssueSeverity.CRITICAL)


